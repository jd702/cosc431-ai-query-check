"""Generate the LaTeX appendices from the repo's data files.

    python scripts/make_latex_appendices.py
    cd docs/latex && tectonic deliverable1.tex

Writes docs/latex/generated/{ddl.sql,questions.tex} so the PDF can never drift from
data/questions.json, data/gold_results.json or sql/normalized_schema.sql.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.paths import DATA, QUESTIONS, SCHEMA_DDL  # noqa: E402

OUT = ROOT / "docs" / "latex" / "generated"

ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex_escape(text: str) -> str:
    return "".join(ESCAPES.get(ch, ch) for ch in str(text))


def fmt_cell(value) -> str:
    if value is None:
        return r"\textsc{null}"
    if isinstance(value, float):
        return f"{value:.4g}"
    return tex_escape(value)


def fmt_row(row) -> str:
    return "(" + ", ".join(fmt_cell(v) for v in row) + ")"


def result_summary(rows, limit_chars=180) -> str:
    """First rows of the result, truncated so the appendix stays readable."""
    shown, out = [], 0
    for row in rows:
        text = fmt_row(row)
        if shown and out + len(text) > limit_chars:
            shown.append(r"\ldots")
            break
        shown.append(text)
        out += len(text)
    return ", ".join(shown)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    questions = json.loads(QUESTIONS.read_text(encoding="utf-8"))
    gold = json.loads((DATA / "gold_results.json").read_text(encoding="utf-8"))

    (OUT / "ddl.sql").write_text(SCHEMA_DDL.read_text(encoding="utf-8"), encoding="utf-8")

    parts = [
        "% GENERATED by scripts/make_latex_appendices.py -- do not edit by hand.",
        "",
        "\\noindent Each entry gives the natural-language question as sent to the models, its",
        "verified gold SQL, and the result that SQL returns against \\texttt{data/chinook.db}.",
        "Owner initials identify the team member who verified the answer.",
        "",
    ]
    for q in questions:
        rows = [tuple(r) for r in gold.get(q["id"], [])]
        notes = q["adaptation_notes"].strip()
        parts += [
            f"\\subsection*{{{q['id']} --- {tex_escape(q['question'])}}}",
            "",
            "\\begin{tabular}{@{}ll@{}}",
            f"\\textbf{{Difficulty}} & {tex_escape(q['difficulty'])} \\\\",
            f"\\textbf{{Shape}} & {tex_escape(q['category'])} \\\\",
            f"\\textbf{{Source}} & {tex_escape(q['spider_source'])} \\\\",
            f"\\textbf{{Verified by}} & {tex_escape(q['owner'])} \\\\",
            f"\\textbf{{Row order matters}} & {'yes' if q.get('order_matters') else 'no'} \\\\",
            "\\end{tabular}",
            "",
            "\\begin{lstlisting}",
            q["gold_sql"].strip(),
            "\\end{lstlisting}",
            "",
            f"\\noindent\\textbf{{Result}} ({len(rows)} "
            f"row{'s' if len(rows) != 1 else ''}): {result_summary(rows)}",
            "",
        ]
        if notes and notes.lower() != "none needed":
            parts += [f"\\noindent\\textbf{{Adaptation}}: {tex_escape(notes)}", ""]

    (OUT / "questions.tex").write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT / 'ddl.sql'} and {OUT / 'questions.tex'} ({len(questions)} questions)")


if __name__ == "__main__":
    main()
